'''
找出進步的學生系統
【問題描述】某班級學生進行了兩次期末模擬考，
兩次的成績分別依序存放在 exam1（第一次考試）與 exam2（第二次考試）兩個串列中。
這兩個串列具有相同的對應順序，也就是說，同一個索引值代表的是同一位學生。

                               exam1 = [70, 85, 60, 90, 55]
                               exam2 = [80, 78, 75, 92, 70]

請撰寫一個 Python 程式，利用迴圈與索引值，找出第二次考試比第一次考試「進步」的學生，並在螢幕上輸出該學生的「第幾位」與「進步的分數」。
'''

exam1 = [70, 85, 60, 90, 55]
exam2 = [80, 78, 75, 92, 70]
for i in range(len(exam1)):
  sc = exam2[i] - exam1[i]
  if sc > 0:
    print(f'第{(i + 1)}個學生，第二次考試較第一次考試進步:{sc}分')
