'''
找出不及格學生
【問題描述】已知某班級有 6 位學生的期末成績，分數依序存放在串列 scores 當中。

              scores = [85, 42, 76, 58, 91, 39]

請撰寫一個 Python 程式，指定使用 range(len(scores)) 的索引值迴圈結構，
逐一檢查所有學生的成績：當發現學生的分數低於 60 分（不及格）時，程式必須在螢幕上輸出該學生的「位數」與「分數」。

【預期輸出結果】

             第二位 不及格，成績：42

             第四位 不及格，成績：58

             第六位 不及格，成績：39
'''

scores = [85, 42, 76, 58, 91, 39]
for i in range(len(scores)):
  if scores[i] < 60:
    print(f'第{(i+1)}個學生，不及格，成績:{scores[i]}')